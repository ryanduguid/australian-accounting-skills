//! Writes the per-skill last-changed table from git history.
//!
//! The table holds dates only, never a commit id, so a squash merge that drops
//! the branch commit that last wrote it leaves it valid.

use crate::{Result, discover_skills, git, platform_text, read_text, replace_file, within_root};
use std::{
    collections::BTreeMap,
    ffi::OsString,
    io::{self, Write},
    path::{Path, PathBuf},
};

const OUTPUT: &str = "docs/skill-last-changed.md";
const HISTORY: &str =
    "https://github.com/ryanduguid/australian-accounting-skills/commits/main/.claude/skills";

/// The table for `rows` of (skill, ISO date), or an error naming a skill with no date.
pub fn render(rows: &[(String, String)]) -> Result<String> {
    let mut text = String::from(
        "# When each skill last changed\n\n\
         Generated by `accounting-skills last-changed --write`. Each date is the day of the \
         last commit to touch that skill's folder, so it shows when the files changed, not \
         when a person reviewed them. Each link opens the skill's current history on GitHub, \
         which can be newer than this table.\n\n\
         | Skill | Last changed |\n| --- | --- |\n",
    );
    for (skill, date) in rows {
        if date.is_empty() {
            return Err(format!("{skill} has no commit history").into());
        }
        text.push_str(&format!("| [`{skill}`]({HISTORY}/{skill}) | {date} |\n"));
    }
    Ok(text)
}

/// Each skill and date the recorded table lists.
fn recorded_dates(text: &str) -> BTreeMap<&str, &str> {
    text.lines()
        .filter_map(|line| {
            let (skill, rest) = line.strip_prefix("| [`")?.split_once("`](")?;
            let date = rest.split_once(") | ")?.1.strip_suffix(" |")?;
            Some((skill, date))
        })
        .collect()
}

/// The day the table first fell behind: for each skill whose row is wrong, the
/// first change to it dated after its recorded date (any change, if unlisted).
fn stale_since(root: &Path, recorded: &str, rows: &[(String, String)]) -> Result<String> {
    let listed = recorded_dates(recorded);
    let mut first: Option<String> = None;
    for (skill, date) in rows {
        let previous = listed.get(skill.as_str()).copied();
        if previous == Some(date.as_str()) {
            continue;
        }
        let path = format!(".claude/skills/{skill}");
        let history = git(root, &["log", "--reverse", "--format=%cs", "--", &path])?;
        let day = history
            .lines()
            .find(|day| previous.is_none_or(|previous| *day > previous))
            .unwrap_or(date)
            .to_string();
        if first.as_ref().is_none_or(|first| day < *first) {
            first = Some(day);
        }
    }
    Ok(first.unwrap_or_default())
}

/// Runs the `last-changed` command. `--check` exits 2 when the table is stale
/// and prints the day it first fell behind as `stale since YYYY-MM-DD`.
pub fn cli(args: impl Iterator<Item = OsString>) -> Result<u8> {
    let mut args = args;
    let mut root = std::env::current_dir()?;
    let mut write = false;
    let mut check = false;
    while let Some(arg) = args.next() {
        match arg.to_str() {
            Some("--root") => {
                root = PathBuf::from(args.next().ok_or("--root requires a path")?);
            }
            Some("--write") => write = true,
            Some("--check") => check = true,
            _ => {
                return Err(
                    "usage: accounting-skills last-changed [--root PATH] [--write | --check]"
                        .into(),
                );
            }
        }
    }
    if write && check {
        return Err("--write and --check are mutually exclusive".into());
    }
    if !git(&root, &["rev-parse", "--show-prefix"])?.is_empty() {
        return Err("--root must be the top of the checkout".into());
    }
    if git(&root, &["rev-parse", "--is-shallow-repository"])? == "true" {
        return Err("a shallow clone cannot date skills; use a full clone".into());
    }
    let skills = discover_skills(&root)?;
    if skills.is_empty() {
        return Err("--root has no skills under .claude/skills".into());
    }
    let mut rows = Vec::new();
    for skill in skills {
        let path = format!(".claude/skills/{skill}");
        let date = git(&root, &["log", "-1", "--format=%cs", "--", &path])?;
        rows.push((skill, date));
    }
    let text = render(&rows)?;
    if check {
        let recorded = read_text(&within_root(&root, Path::new(OUTPUT))?)?.replace("\r\n", "\n");
        if recorded != text {
            eprintln!("{OUTPUT} is stale. Run accounting-skills last-changed --write from main.");
            println!("stale since {}", stale_since(&root, &recorded, &rows)?);
            return Ok(2);
        }
        return Ok(0);
    }
    if write {
        replace_file(
            &within_root(&root, Path::new(OUTPUT))?,
            &platform_text(&text),
        )?;
    } else {
        io::stdout().write_all(platform_text(&text).as_bytes())?;
    }
    Ok(0)
}

#[cfg(test)]
mod tests {
    use super::{OUTPUT, cli, git, render, stale_since};
    use crate::read_text;
    use std::{ffi::OsString, fs, path::Path, process::Command};
    use tempfile::{TempDir, tempdir};

    fn commit_skill(root: &Path, skill: &str, when: &str) {
        let folder = root.join(".claude/skills").join(skill);
        fs::create_dir_all(&folder).unwrap();
        fs::write(folder.join("SKILL.md"), format!("fabricated {when}\n")).unwrap();
        for args in [
            vec!["add", "."],
            vec![
                "-c",
                "user.name=Test",
                "-c",
                "user.email=test@example.invalid",
                "-c",
                "commit.gpgsign=false",
                "commit",
                "-q",
                "--no-verify",
                "-m",
                skill,
            ],
        ] {
            let status = Command::new("git")
                .args(args)
                .env("GIT_AUTHOR_DATE", when)
                .env("GIT_COMMITTER_DATE", when)
                .current_dir(root)
                .status()
                .unwrap();
            assert!(status.success());
        }
    }

    fn checkout() -> TempDir {
        let directory = tempdir().unwrap();
        fs::create_dir(directory.path().join("docs")).unwrap();
        git(directory.path(), &["init", "-q"]).unwrap();
        commit_skill(directory.path(), "older-skill", "2026-01-02T12:00:00+11:00");
        commit_skill(directory.path(), "newer-skill", "2026-03-04T12:00:00+11:00");
        directory
    }

    fn run(root: &Path, extra: &[&str]) -> Result<u8, String> {
        let mut args = vec![OsString::from("--root"), root.into()];
        args.extend(extra.iter().map(OsString::from));
        cli(args.into_iter()).map_err(|error| error.to_string())
    }

    #[test]
    fn writes_each_skill_with_the_date_of_its_own_last_commit() {
        let directory = checkout();
        assert_eq!(run(directory.path(), &["--write"]), Ok(0));
        let text = read_text(&directory.path().join(OUTPUT)).unwrap();
        assert!(!text.contains("commit "), "the table names no commit");
        assert!(text.contains("/older-skill) | 2026-01-02 |\n"));
        assert!(text.contains("/newer-skill) | 2026-03-04 |\n"));
    }

    #[test]
    fn prints_without_writing_by_default() {
        let directory = checkout();
        assert_eq!(run(directory.path(), &[]), Ok(0));
        assert!(!directory.path().join(OUTPUT).exists());
    }

    #[test]
    fn refuses_a_root_below_the_top_of_the_checkout() {
        let directory = checkout();
        let error = run(&directory.path().join("docs"), &["--write"]);
        assert_eq!(error.unwrap_err(), "--root must be the top of the checkout");
    }

    #[test]
    fn refuses_a_folder_that_is_not_a_checkout() {
        let directory = tempdir().unwrap();
        let error = run(directory.path(), &[]).unwrap_err();
        assert!(error.starts_with("git rev-parse --show-prefix failed:"));
    }

    #[test]
    fn refuses_a_checkout_with_no_skills() {
        let directory = tempdir().unwrap();
        git(directory.path(), &["init", "-q"]).unwrap();
        let error = run(directory.path(), &[]).unwrap_err();
        assert_eq!(error, "--root has no skills under .claude/skills");
    }

    #[test]
    fn refuses_a_shallow_clone() {
        let directory = checkout();
        let head = git(directory.path(), &["rev-parse", "HEAD"]).unwrap();
        fs::write(directory.path().join(".git/shallow"), head + "\n").unwrap();
        let error = run(directory.path(), &[]).unwrap_err();
        assert!(error.contains("shallow clone"), "{error}");
    }

    #[test]
    fn refuses_bad_arguments() {
        let no_path = cli([OsString::from("--root")].into_iter());
        assert!(no_path.unwrap_err().to_string().contains("requires a path"));
        let unknown = cli([OsString::from("--unknown")].into_iter());
        assert!(unknown.unwrap_err().to_string().starts_with("usage:"));
        let directory = checkout();
        assert!(run(directory.path(), &["--write", "--check"]).is_err());
    }

    #[test]
    fn checks_dates_without_changing_the_snapshot_commit() {
        let directory = checkout();
        let root = directory.path();
        assert_eq!(run(root, &["--write"]), Ok(0));
        let recorded = read_text(&root.join(OUTPUT)).unwrap();
        git(root, &["add", "--", OUTPUT]).unwrap();
        git(
            root,
            &[
                "-c",
                "user.name=Test",
                "-c",
                "user.email=test@example.invalid",
                "-c",
                "commit.gpgsign=false",
                "commit",
                "--no-verify",
                "-qm",
                "Record the snapshot",
            ],
        )
        .unwrap();
        assert_eq!(run(root, &["--check"]), Ok(0));
        commit_skill(root, "older-skill", "2026-01-02T20:00:00+11:00");
        assert_eq!(run(root, &["--check"]), Ok(0));
        commit_skill(root, "older-skill", "2026-04-05T12:00:00+10:00");
        assert_eq!(run(root, &["--check"]), Ok(2));
        assert_eq!(read_text(&root.join(OUTPUT)).unwrap(), recorded);
        assert_eq!(run(root, &["--write"]), Ok(0));
        assert_eq!(run(root, &["--check"]), Ok(0));
    }

    fn commit_all(root: &Path, message: &str, when: &str) {
        let status = Command::new("git")
            .args([
                "-c",
                "user.name=Test",
                "-c",
                "user.email=test@example.invalid",
            ])
            .args([
                "-c",
                "commit.gpgsign=false",
                "commit",
                "--no-verify",
                "-qm",
                message,
            ])
            .env("GIT_AUTHOR_DATE", when)
            .env("GIT_COMMITTER_DATE", when)
            .current_dir(root)
            .status()
            .unwrap();
        assert!(status.success());
    }

    #[test]
    fn a_table_written_on_a_branch_survives_a_squash_merge() {
        let directory = checkout();
        let root = directory.path();
        let main = git(root, &["rev-parse", "--abbrev-ref", "HEAD"]).unwrap();
        git(root, &["switch", "-qc", "topic"]).unwrap();
        commit_skill(root, "newer-skill", "2026-03-04T15:00:00+11:00");
        assert_eq!(run(root, &["--write"]), Ok(0));
        git(root, &["add", "--", OUTPUT]).unwrap();
        commit_all(root, "Refresh on the branch", "2026-03-04T15:30:00+11:00");
        git(root, &["switch", "-q", &main]).unwrap();
        git(root, &["merge", "--squash", "-q", "topic"]).unwrap();
        // The squash commit replaces both branch commits, as a squash merge does.
        commit_all(root, "Squash", "2026-03-04T18:00:00+11:00");
        git(root, &["branch", "-qD", "topic"]).unwrap();
        assert_eq!(run(root, &["--check"]), Ok(0));
    }

    #[test]
    fn dates_a_stale_table_from_the_first_change_it_missed() {
        let directory = checkout();
        let root = directory.path();
        let recorded = render(&[("older-skill".into(), "2026-01-02".into())]).unwrap();
        commit_skill(root, "older-skill", "2026-04-05T12:00:00+10:00");
        commit_skill(root, "older-skill", "2026-05-06T12:00:00+10:00");
        let rows = [
            ("newer-skill".to_string(), "2026-03-04".to_string()),
            ("older-skill".to_string(), "2026-05-06".to_string()),
        ];
        assert_eq!(stale_since(root, &recorded, &rows).unwrap(), "2026-03-04");
        let only_older = &rows[1..];
        assert_eq!(
            stale_since(root, &recorded, only_older).unwrap(),
            "2026-04-05"
        );
        let current = render(&rows).unwrap();
        assert_eq!(stale_since(root, &current, &rows).unwrap(), "");
    }

    #[test]
    fn renders_one_linked_row_per_skill() {
        let rows = vec![("bas-preparation".to_string(), "2026-11-05".to_string())];
        let text = render(&rows).unwrap();
        assert!(text.contains(
            "| [`bas-preparation`](https://github.com/ryanduguid/australian-accounting-skills\
             /commits/main/.claude/skills/bas-preparation) | 2026-11-05 |\n"
        ));
    }

    #[cfg(unix)]
    #[test]
    fn write_refuses_a_docs_folder_linked_outside_the_checkout() {
        let directory = checkout();
        let outside = tempdir().unwrap();
        fs::remove_dir(directory.path().join("docs")).unwrap();
        std::os::unix::fs::symlink(outside.path(), directory.path().join("docs")).unwrap();
        let error = run(directory.path(), &["--write"]).unwrap_err();
        assert!(error.contains("escapes"), "{error}");
        assert_eq!(fs::read_dir(outside.path()).unwrap().count(), 0);
    }

    #[test]
    fn refuses_a_skill_with_no_history() {
        let rows = vec![("new-skill".to_string(), String::new())];
        let error = render(&rows).unwrap_err().to_string();
        assert!(error.contains("new-skill has no commit history"));
    }
}
