//! Writes the per-skill last-changed table from git history.

use crate::{Result, platform_text, replace_file};
use std::{
    ffi::OsString,
    fs,
    io::{self, Write},
    path::{Path, PathBuf},
    process::Command,
};

const OUTPUT: &str = "docs/skill-last-changed.md";
const HISTORY: &str =
    "https://github.com/ryanduguid/australian-accounting-skills/commits/main/.claude/skills";

fn git(root: &Path, args: &[&str]) -> Result<String> {
    let output = Command::new("git")
        .arg("-C")
        .arg(root)
        .args(args)
        .output()?;
    if !output.status.success() {
        return Err(format!("git {} failed", args.join(" ")).into());
    }
    Ok(String::from_utf8(output.stdout)?.trim().to_string())
}

fn skills(root: &Path) -> Result<Vec<String>> {
    let mut names = Vec::new();
    for entry in fs::read_dir(root.join(".claude/skills"))? {
        let path = entry?.path();
        if path.join("SKILL.md").is_file() {
            let name = path.file_name().ok_or("skill folder has no name")?;
            names.push(name.to_str().ok_or("skill name is not UTF-8")?.to_string());
        }
    }
    names.sort();
    Ok(names)
}

/// The table for `rows` of (skill, ISO date), or an error naming a skill with no date.
pub fn render(commit: &str, rows: &[(String, String)]) -> Result<String> {
    let mut text = format!(
        "# When each skill last changed\n\n\
         Generated by `accounting-skills last-changed --write` at commit {commit}. Each date is \
         the last commit to touch that skill's folder, so it shows when the files changed, not \
         when a person reviewed them. Each link opens the skill's current history on GitHub, \
         which can be newer than this table.\n\n\
         | Skill | Last changed |\n| --- | --- |\n"
    );
    for (skill, date) in rows {
        if date.is_empty() {
            return Err(format!("{skill} has no commit history").into());
        }
        text.push_str(&format!("| [`{skill}`]({HISTORY}/{skill}) | {date} |\n"));
    }
    Ok(text)
}

/// Runs the `last-changed` command.
pub fn cli(args: impl Iterator<Item = OsString>) -> Result<u8> {
    let mut args = args;
    let mut root = std::env::current_dir()?;
    let mut write = false;
    while let Some(arg) = args.next() {
        match arg.to_str() {
            Some("--root") => {
                root = PathBuf::from(args.next().ok_or("--root requires a path")?);
            }
            Some("--write") => write = true,
            _ => {
                return Err("usage: accounting-skills last-changed [--root PATH] [--write]".into());
            }
        }
    }
    if git(&root, &["rev-parse", "--is-shallow-repository"])? == "true" {
        return Err("a shallow clone cannot date skills; use a full clone".into());
    }
    let mut rows = Vec::new();
    for skill in skills(&root)? {
        let path = format!(".claude/skills/{skill}");
        let date = git(&root, &["log", "-1", "--format=%cs", "--", &path])?;
        rows.push((skill, date));
    }
    let commit = git(&root, &["rev-parse", "--short", "HEAD"])?;
    let text = render(&commit, &rows)?;
    if write {
        replace_file(&root.join(OUTPUT), &platform_text(&text))?;
    } else {
        io::stdout().write_all(platform_text(&text).as_bytes())?;
    }
    Ok(0)
}

#[cfg(test)]
mod tests {
    use super::render;

    #[test]
    fn renders_one_linked_row_per_skill() {
        let rows = vec![("bas-preparation".to_string(), "2026-11-05".to_string())];
        let text = render("abc1234", &rows).unwrap();
        assert!(text.contains("at commit abc1234"));
        assert!(text.contains(
            "| [`bas-preparation`](https://github.com/ryanduguid/australian-accounting-skills\
             /commits/main/.claude/skills/bas-preparation) | 2026-11-05 |\n"
        ));
    }

    #[test]
    fn refuses_a_skill_with_no_history() {
        let rows = vec![("new-skill".to_string(), String::new())];
        let error = render("abc1234", &rows).unwrap_err().to_string();
        assert!(error.contains("new-skill has no commit history"));
    }
}
